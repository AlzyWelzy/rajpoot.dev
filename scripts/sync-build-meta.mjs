#!/usr/bin/env node
/**
 * Keeps two hand-maintained dates honest. Runs from `pnpm build` (and can be
 * run on its own with `pnpm sync:meta`).
 *
 *  1. lib/generated/content-updated.ts — the date content last actually
 *     changed, from git. Feeds the sitemap's `lastmod` and JSON-LD's
 *     `dateModified`, which used to be a constant someone had to remember to
 *     bump and therefore drifted.
 *
 *  2. public/.well-known/security.txt — RFC 9116 requires an `Expires` in the
 *     future; a hardcoded one silently becomes invalid. Rolled forward to a
 *     year out whenever it is within 90 days of lapsing.
 *
 * Both outputs are committed. That is deliberate: a fresh clone must typecheck
 * and test without running a build step first, and rewriting only on real
 * change keeps the git churn near zero.
 *
 * Everything here degrades to "leave the committed value alone" if git is
 * unavailable (shallow CI clones, tarball installs), so the build never fails
 * over metadata.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const GENERATED_PATH = join(root, "lib/generated/content-updated.ts");
const SECURITY_TXT_PATH = join(root, "public/.well-known/security.txt");

// Files whose changes count as a content update. Deliberately excludes config,
// tests, and CI: a dependency bump is not a reason to tell Google the page
// changed. lib/generated is excluded too, or it would keep re-triggering
// itself.
const CONTENT_PATHS = [
  "lib/data.ts",
  "lib/seo.ts",
  "app/page.tsx",
  "components",
  "public",
];

const DAY_MS = 24 * 60 * 60 * 1000;

/** ISO date (YYYY-MM-DD) of the last commit touching any content path. */
function gitContentDate() {
  try {
    const out = execFileSync(
      "git",
      ["log", "-1", "--format=%cs", "--", ...CONTENT_PATHS],
      { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    ).trim();
    return /^\d{4}-\d{2}-\d{2}$/.test(out) ? out : null;
  } catch {
    // No git, shallow clone with no matching commit, or not a repo.
    return null;
  }
}

function syncContentUpdated() {
  const date = gitContentDate();
  if (!date) {
    console.log(
      "[build-meta] no git content date available — keeping the committed value",
    );
    return;
  }

  const contents = `// Generated by scripts/sync-build-meta.mjs — do not edit by hand.
// Date of the last commit touching site content (copy, data, assets), used for
// the sitemap's lastmod and JSON-LD's dateModified. It trails the commit that
// regenerates it by one, which is well inside the resolution search engines
// treat this signal at.
export const contentUpdated = "${date}" as const;
`;

  const existing = existsSync(GENERATED_PATH)
    ? readFileSync(GENERATED_PATH, "utf8")
    : null;
  if (existing === contents) {
    console.log(`[build-meta] content-updated already ${date}`);
    return;
  }

  mkdirSync(dirname(GENERATED_PATH), { recursive: true });
  writeFileSync(GENERATED_PATH, contents);
  console.log(`[build-meta] content-updated -> ${date}`);
}

function syncSecurityTxt() {
  if (!existsSync(SECURITY_TXT_PATH)) {
    console.log("[build-meta] no security.txt — skipping");
    return;
  }

  const original = readFileSync(SECURITY_TXT_PATH, "utf8");
  const match = original.match(/^Expires:\s*(.+)$/m);
  const current = match?.[1] ? Date.parse(match[1].trim()) : NaN;
  const now = Date.now();

  // Only roll it forward when it is actually close to lapsing, so routine
  // builds don't produce a diff.
  if (Number.isFinite(current) && current - now > 90 * DAY_MS) {
    console.log("[build-meta] security.txt Expires still comfortably valid");
    return;
  }

  const next = new Date(now + 365 * DAY_MS).toISOString();
  const updated = match
    ? original.replace(/^Expires:\s*.+$/m, `Expires: ${next}`)
    : `${original.trimEnd()}\nExpires: ${next}\n`;

  writeFileSync(SECURITY_TXT_PATH, updated);
  console.log(`[build-meta] security.txt Expires -> ${next}`);
}

syncContentUpdated();
syncSecurityTxt();
